const lastUsed = new Map();

export function resolve(event) {
  const cands = L.filter((e) => e.event === event);
  if (!cands.length) return null;
  const last = lastUsed.get(event);
  const pool = [];
  for (const c of cands) {
    const w = (c.weight ?? 1) * (c === last ? 0.15 : 1);
    for (let i = 0; i < Math.max(1, Math.round(w * 10)); i++) pool.push(c);
  }
  const chosen = pick(pool);
  lastUsed.set(event, chosen);
  return { entry: chosen, line: pick(chosen.lines) };
}

